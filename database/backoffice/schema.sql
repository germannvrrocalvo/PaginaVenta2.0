BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Credenciales y sesiones exclusivas de CoreAdmin. No se reutilizan las
-- cuentas de cliente de la tienda.
CREATE TABLE IF NOT EXISTS backoffice_admins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    name          VARCHAR(120) NOT NULL,
    password_hash TEXT         NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_backoffice_admins_email
    ON backoffice_admins (lower(email));

CREATE TABLE IF NOT EXISTS backoffice_sessions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   BIGINT      NOT NULL REFERENCES backoffice_admins(id) ON DELETE CASCADE,
    token_hash TEXT        NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_backoffice_sessions_admin
    ON backoffice_sessions(admin_id);

-- Proyección de pedidos que n8n mantiene a partir de order.created y
-- order.status_changed. Nunca sustituye a las tablas transaccionales de tienda.
CREATE TABLE IF NOT EXISTS orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       TEXT        NOT NULL UNIQUE,
    event_id       TEXT        NOT NULL UNIQUE,
    customer_id    TEXT,
    customer_email TEXT,
    total_amount   NUMERIC     NOT NULL DEFAULT 0,
    currency       TEXT        NOT NULL DEFAULT 'EUR',
    order_status   TEXT        NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    integrated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Campos operativos y financieros replicados desde la tienda. Las columnas se
-- añaden de forma idempotente para actualizar instalaciones ya existentes sin
-- borrar los pedidos que n8n haya registrado previamente.
ALTER TABLE orders ADD COLUMN IF NOT EXISTS event_id TEXT;
UPDATE orders
SET event_id = 'legacy:' || order_id
WHERE event_id IS NULL;
ALTER TABLE orders ALTER COLUMN event_id SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_backoffice_orders_event_id ON orders(event_id);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_name TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS customer_phone TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_address JSONB NOT NULL DEFAULT '{}'::jsonb;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS subtotal_amount NUMERIC NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_amount NUMERIC NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_amount NUMERIC NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tax_rate NUMERIC NOT NULL DEFAULT 21;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tax_base_amount NUMERIC NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS tax_amount NUMERIC NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_status TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_method TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_reference TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS paypal_order_id TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS paypal_capture_id TEXT;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS paid_at TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS receipt_sent_at TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS source_updated_at TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS source_synced_at TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS source_system TEXT NOT NULL DEFAULT 'n8n';
CREATE INDEX IF NOT EXISTS idx_backoffice_orders_created_at ON orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_backoffice_orders_source_system ON orders(source_system);
CREATE INDEX IF NOT EXISTS idx_backoffice_orders_payment_status ON orders(payment_status);

CREATE TABLE IF NOT EXISTS order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     TEXT    NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id   TEXT    NOT NULL,
    product_name TEXT,
    quantity     INT     NOT NULL CHECK (quantity > 0),
    unit_price   NUMERIC NOT NULL CHECK (unit_price >= 0),
    line_total   NUMERIC NOT NULL CHECK (line_total >= 0),
    UNIQUE (order_id, product_id)
);
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS source_product_id TEXT;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS variant_id TEXT;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS brand TEXT;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS variant_type TEXT;
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS variant_value TEXT;
CREATE INDEX IF NOT EXISTS idx_backoffice_order_items_order ON order_items(order_id);

CREATE TABLE IF NOT EXISTS integration_logs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id           TEXT        NOT NULL,
    event_type         TEXT        NOT NULL,
    order_id           TEXT,
    workflow_name      TEXT,
    execution_id       TEXT,
    integration_status TEXT        NOT NULL,
    error_type         TEXT,
    error_message      TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_backoffice_integration_event ON integration_logs(event_id);
CREATE INDEX IF NOT EXISTS idx_backoffice_integration_created ON integration_logs(created_at DESC);

-- Incidencias y propuestas del agente comparten la BD del back office.
CREATE TABLE IF NOT EXISTS incidents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id       UUID        NOT NULL DEFAULT gen_random_uuid(),
    order_id          TEXT,
    customer_id       TEXT        NOT NULL,
    incident_type     TEXT        NOT NULL,
    description       TEXT        NOT NULL,
    priority          TEXT        NOT NULL DEFAULT 'medium',
    status            TEXT        NOT NULL DEFAULT 'open',
    telegram_chat_id  TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at       TIMESTAMPTZ,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE incidents ADD COLUMN IF NOT EXISTS incident_id UUID;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS source_reference TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS customer_name TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS subject TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS analysis_status VARCHAR(20) NOT NULL DEFAULT 'idle';
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS analysis_requested_at TIMESTAMPTZ;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS analysis_error TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS telegram_message_id TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS telegram_notified_at TIMESTAMPTZ;

-- El número de pedido de una incidencia lo introduce el cliente y puede ser
-- incorrecto o pertenecer a un pedido que aún no se haya proyectado desde n8n.
-- Debe conservarse para que el agente pueda investigarlo, sin impedir que la
-- incidencia llegue al back office.
ALTER TABLE incidents DROP CONSTRAINT IF EXISTS incidents_order_id_fkey;

UPDATE incidents SET incident_id = gen_random_uuid() WHERE incident_id IS NULL;
ALTER TABLE incidents ALTER COLUMN incident_id SET DEFAULT gen_random_uuid();
ALTER TABLE incidents ALTER COLUMN incident_id SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_backoffice_incidents_incident_id
    ON incidents(incident_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_backoffice_incidents_source_reference
    ON incidents(source_reference) WHERE source_reference IS NOT NULL;

CREATE TABLE IF NOT EXISTS agent_actions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id     UUID,
    case_type       TEXT,
    consulted_data  JSONB,
    proposed_action TEXT,
    justification   TEXT,
    confidence      NUMERIC,
    risks           TEXT,
    review_status   TEXT        NOT NULL DEFAULT 'pending_review',
    reviewed_by     TEXT,
    reviewed_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE agent_actions ADD COLUMN IF NOT EXISTS source_action_id BIGINT;
ALTER TABLE agent_actions ADD COLUMN IF NOT EXISTS execution_status TEXT NOT NULL DEFAULT 'not_requested';
ALTER TABLE agent_actions ADD COLUMN IF NOT EXISTS executed_at TIMESTAMPTZ;
ALTER TABLE agent_actions ADD COLUMN IF NOT EXISTS execution_error TEXT;
ALTER TABLE agent_actions ADD COLUMN IF NOT EXISTS telegram_message_id TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_agent_actions_source_action
    ON agent_actions(source_action_id) WHERE source_action_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_agent_actions_incident_review
    ON agent_actions(incident_id, review_status, created_at DESC);

-- La aprobación humana y el evento de salida se confirman en una sola
-- transacción. El worker entrega después a n8n; un fallo de Telegram no pierde
-- la decisión ni obliga al administrador a aprobar de nuevo.
CREATE TABLE IF NOT EXISTS agent_action_outbox (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         TEXT        NOT NULL UNIQUE,
    event_type       TEXT        NOT NULL,
    action_id        BIGINT      NOT NULL REFERENCES agent_actions(id) ON DELETE CASCADE,
    payload          JSONB       NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'pending',
    attempts         INT         NOT NULL DEFAULT 0,
    next_attempt_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    locked_at        TIMESTAMPTZ,
    last_http_status INT,
    last_error       TEXT,
    delivered_at     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_agent_action_outbox_due
    ON agent_action_outbox(status, next_attempt_at, created_at);

COMMIT;
