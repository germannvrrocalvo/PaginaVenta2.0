BEGIN;

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- Credenciales y sesiones exclusivas de CoreAdmin. No se reutilizan las
-- cuentas de cliente de la tienda.
CREATE TABLE IF NOT EXISTS backoffice_admins (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(254) NOT NULL,
    name          VARCHAR(120) NOT NULL,
    password_hash TEXT         NOT NULL,
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_backoffice_admins_email
    ON backoffice_admins (lower(email));

CREATE TABLE IF NOT EXISTS backoffice_sessions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id   BIGINT      NOT NULL REFERENCES backoffice_admins(id) ON DELETE CASCADE,
    token_hash TEXT        NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_backoffice_sessions_admin
    ON backoffice_sessions(admin_id);

-- Proyección de pedidos que n8n mantiene a partir de order.created y
-- order.status_changed. Nunca sustituye a las tablas transaccionales de tienda.
CREATE TABLE IF NOT EXISTS orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       TEXT        NOT NULL UNIQUE,
    customer_id    TEXT,
    customer_email TEXT,
    total_amount   NUMERIC     NOT NULL DEFAULT 0,
    currency       TEXT        NOT NULL DEFAULT 'EUR',
    order_status   TEXT        NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    integrated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_backoffice_orders_created_at ON orders(created_at DESC);

CREATE TABLE IF NOT EXISTS order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     TEXT    NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id   TEXT    NOT NULL,
    product_name TEXT,
    quantity     INT     NOT NULL CHECK (quantity > 0),
    unit_price   NUMERIC NOT NULL CHECK (unit_price >= 0),
    line_total   NUMERIC NOT NULL CHECK (line_total >= 0),
    UNIQUE (order_id, product_id)
);
CREATE INDEX IF NOT EXISTS idx_backoffice_order_items_order ON order_items(order_id);

CREATE TABLE IF NOT EXISTS integration_logs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id           TEXT        NOT NULL,
    event_type         TEXT        NOT NULL,
    order_id           TEXT,
    workflow_name      TEXT,
    execution_id       TEXT,
    integration_status TEXT        NOT NULL,
    error_type         TEXT,
    error_message      TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_backoffice_integration_event ON integration_logs(event_id);
CREATE INDEX IF NOT EXISTS idx_backoffice_integration_created ON integration_logs(created_at DESC);

-- Incidencias y propuestas del agente comparten la BD del back office.
CREATE TABLE IF NOT EXISTS incidents (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id       UUID        NOT NULL DEFAULT gen_random_uuid(),
    order_id          TEXT,
    customer_id       TEXT        NOT NULL,
    incident_type     TEXT        NOT NULL,
    description       TEXT        NOT NULL,
    priority          TEXT        NOT NULL DEFAULT 'medium',
    status            TEXT        NOT NULL DEFAULT 'open',
    telegram_chat_id  TEXT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at       TIMESTAMPTZ,
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE incidents ADD COLUMN IF NOT EXISTS incident_id UUID;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS source_reference TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS customer_name TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS subject TEXT;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS analysis_status VARCHAR(20) NOT NULL DEFAULT 'idle';
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS analysis_requested_at TIMESTAMPTZ;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS analysis_error TEXT;

UPDATE incidents SET incident_id = gen_random_uuid() WHERE incident_id IS NULL;
ALTER TABLE incidents ALTER COLUMN incident_id SET DEFAULT gen_random_uuid();
ALTER TABLE incidents ALTER COLUMN incident_id SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_backoffice_incidents_incident_id
    ON incidents(incident_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_backoffice_incidents_source_reference
    ON incidents(source_reference) WHERE source_reference IS NOT NULL;

CREATE TABLE IF NOT EXISTS agent_actions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id     UUID,
    case_type       TEXT,
    consulted_data  JSONB,
    proposed_action TEXT,
    justification   TEXT,
    confidence      NUMERIC,
    risks           TEXT,
    review_status   TEXT        NOT NULL DEFAULT 'pending_review',
    reviewed_by     TEXT,
    reviewed_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
ALTER TABLE agent_actions ADD COLUMN IF NOT EXISTS source_action_id BIGINT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_agent_actions_source_action
    ON agent_actions(source_action_id) WHERE source_action_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_agent_actions_incident_review
    ON agent_actions(incident_id, review_status, created_at DESC);

COMMIT;
