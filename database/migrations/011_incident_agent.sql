BEGIN;

CREATE TABLE IF NOT EXISTS incidents (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id     UUID NOT NULL DEFAULT gen_random_uuid(),
    order_id        TEXT,
    customer_id     TEXT NOT NULL,
    incident_type   TEXT NOT NULL,
    description     TEXT NOT NULL,
    priority        TEXT NOT NULL DEFAULT 'medium',
    status          TEXT NOT NULL DEFAULT 'open',
    telegram_chat_id TEXT,
    source_reference TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    resolved_at     TIMESTAMPTZ,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE incidents ADD COLUMN IF NOT EXISTS source_reference TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_incidents_incident_id ON incidents(incident_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_incidents_source_reference
    ON incidents(source_reference) WHERE source_reference IS NOT NULL;

CREATE TABLE IF NOT EXISTS agent_actions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id     UUID,
    case_type       TEXT,
    consulted_data  JSONB,
    proposed_action TEXT,
    justification   TEXT,
    confidence      NUMERIC,
    risks           TEXT,
    review_status   TEXT NOT NULL DEFAULT 'pending_review',
    reviewed_by     TEXT,
    reviewed_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_agent_actions_incident_review
    ON agent_actions(incident_id, review_status, created_at DESC);

ALTER TABLE incidencia ADD COLUMN IF NOT EXISTS agent_incident_id UUID;
ALTER TABLE incidencia ADD COLUMN IF NOT EXISTS agent_analysis_status VARCHAR(20) NOT NULL DEFAULT 'idle';
ALTER TABLE incidencia ADD COLUMN IF NOT EXISTS agent_analysis_requested_at TIMESTAMPTZ;
ALTER TABLE incidencia ADD COLUMN IF NOT EXISTS agent_analysis_error TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_incidencia_agent_incident
    ON incidencia(agent_incident_id) WHERE agent_incident_id IS NOT NULL;

INSERT INTO incidents (
    order_id, customer_id, incident_type, description, priority, status,
    source_reference, created_at, updated_at
)
SELECT i.numero_pedido_indicado, i.email_contacto, 'support_request',
       i.asunto || E'\n\n' || i.descripcion, 'medium',
       CASE i.estado
         WHEN 'resuelta' THEN 'resolved'
         WHEN 'cerrada' THEN 'closed'
         WHEN 'en_curso' THEN 'in_progress'
         ELSE 'open'
       END,
       i.referencia, i.fecha_creacion, i.fecha_creacion
FROM incidencia i
WHERE i.agent_incident_id IS NULL
ON CONFLICT (source_reference) WHERE source_reference IS NOT NULL DO NOTHING;

UPDATE incidencia i
SET agent_incident_id = ai.incident_id
FROM incidents ai
WHERE i.agent_incident_id IS NULL AND ai.source_reference = i.referencia;

COMMIT;
