BEGIN;

CREATE TABLE IF NOT EXISTS integration_outbox (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id           VARCHAR(120) NOT NULL UNIQUE,
    event_type         VARCHAR(60)  NOT NULL CHECK (event_type = 'order.created'),
    payload            JSONB        NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'pending'
                       CHECK (status IN ('pending','processing','retry','delivered','dead_letter')),
    attempts           INT          NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_attempt_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    locked_at          TIMESTAMPTZ,
    delivered_at       TIMESTAMPTZ,
    last_http_status   INT,
    last_error         VARCHAR(500),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_integration_outbox_due
    ON integration_outbox (status, next_attempt_at);

ALTER TABLE integration_outbox ENABLE ROW LEVEL SECURITY;

COMMIT;
